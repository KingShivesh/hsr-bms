import { chromium } from "playwright";
import fs from "node:fs/promises";
import assert from "node:assert/strict";
import { scanRenderedContrast } from "./rendered-contrast.mjs";

const app = "http://127.0.0.1:5181", api = "http://127.0.0.1:8006";
const directory = process.env.POLISH_CONTROLS_REPORT_PATH || "../docs/interaction-polish/controls";
await fs.mkdir(directory, { recursive: true });
const auth = await fetch(api + "/auth/login", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ username: "staff", password: "staff123" }) }).then(r => r.json());
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const report = { checks: [], contrast: [], errors: [], productionMutations: 0 };
try {
  for (const theme of ["dark", "light"]) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    await context.addInitScript(({ auth, theme }) => { localStorage.setItem("theme", theme); for (const key of ["token", "role", "username"]) localStorage.setItem(key, auth[key]); }, { auth, theme });
    const page = await context.newPage();
    page.on("pageerror", error => report.errors.push(error.message));
    await page.goto(app + "/live-floor");
    const end = page.locator(".lf-table-card").first().getByRole("button", { name: "End", exact: true });
    await end.click();
    const drawer = page.locator(".checkout-panel");
    await drawer.getByText("Payment method", { exact: true }).waitFor();
    const toggle = drawer.getByRole("button", { name: "Adjust Time", exact: true });
    assert.equal(await toggle.getAttribute("aria-expanded"), "false");
    await toggle.click();
    assert.equal(await toggle.getAttribute("aria-expanded"), "true");
    await page.waitForTimeout(170);
    const expanded = await toggle.evaluate(button => ({ tag: button.tagName, height: button.getBoundingClientRect().height, background: getComputedStyle(button).backgroundColor, chevron: getComputedStyle(button.querySelector(".ui-disclosure-chevron")).transform }));
    assert.match(expanded.chevron, /matrix\(-1/);
    assert.ok(await drawer.getByRole("button", { name: "Apply Change", exact: true }).isDisabled());
    const notes = drawer.getByLabel("Notes (optional)");
    assert.equal(await notes.evaluate(node => node.tagName), "TEXTAREA");
    await notes.fill("QA unsaved time correction");
    await drawer.getByRole("button", { name: "Cancel", exact: true }).click();
    const confirm = page.getByRole("dialog", { name: "Discard checkout edits?" });
    await confirm.waitFor();
    await page.keyboard.press("Shift+Tab");
    assert.ok(await confirm.evaluate(node => node.contains(document.activeElement)));
    await page.keyboard.press("Tab");
    assert.ok(await confirm.evaluate(node => node.contains(document.activeElement)));
    await page.screenshot({ path: `${directory}/discard-${theme}.png` });
    report.contrast.push(...await scanRenderedContrast(page, { route: "/live-floor", theme, state: "nested-discard-confirm" }));
    await page.keyboard.press("Escape");
    await confirm.waitFor({ state: "hidden" });
    assert.ok(await drawer.isVisible());
    assert.equal(await notes.inputValue(), "QA unsaved time correction");
    await drawer.getByRole("button", { name: "Reset", exact: true }).click();
    assert.equal(await notes.inputValue(), "");
    const started = drawer.getByLabel("Started at", { exact: true });
    const earlier = await started.evaluate(node => { const ms = new Date(node.value).getTime() - 5 * 60000; return new Date(ms - new Date(ms).getTimezoneOffset() * 60000).toISOString().slice(0, 19); });
    await started.fill(earlier);
    await drawer.getByLabel("Time adjustment reason", { exact: true }).selectOption("staff_forgot_to_start");
    assert.ok(await drawer.getByRole("button", { name: "Apply Change", exact: true }).isEnabled());
    await drawer.getByRole("button", { name: "Apply Change", exact: true }).click();
    await drawer.getByText("Duration adjusted", { exact: true }).waitFor();
    report.checks.push({ theme, trustedStaffTimeEditing: true, toggle: expanded, reasonRequired: true, textarea: true, resetWorks: true, nestedEscapeKeepsDraft: true, focusTrap: true });
    await drawer.getByRole("button", { name: "Reset", exact: true }).click();
    await drawer.getByRole("button", { name: "Add name", exact: true }).click();
    await page.waitForTimeout(120);
    const selected = await drawer.getByRole("button", { name: "Add name", exact: true }).evaluate(node => ({ color: getComputedStyle(node).color, background: getComputedStyle(node).backgroundColor, pressed: node.getAttribute("aria-pressed") }));
    assert.equal(selected.pressed, "true");
    await drawer.getByLabel("Name (optional)").fill("QA unsaved name");
    await page.keyboard.press("Escape");
    await confirm.waitFor();
    await confirm.getByRole("button", { name: "Discard edits", exact: true }).click();
    await drawer.waitFor({ state: "hidden" });
    await page.waitForTimeout(50);
    assert.ok(await end.evaluate(node => node === document.activeElement));
    await end.click();
    await drawer.getByText("Payment method", { exact: true }).waitFor();
    assert.ok(await drawer.getByRole("button", { name: "Credit", exact: true }).isDisabled());
    for (const width of [1440, 375, 414]) {
      await page.setViewportSize({ width, height: width === 1440 ? 1100 : 896 });
      await drawer.getByText("Payment method", { exact: true }).scrollIntoViewIfNeeded();
      const metrics = await drawer.evaluate(node => ({ overflow: Math.max(0, document.documentElement.scrollWidth - innerWidth), height: node.getBoundingClientRect().height, buttons: [...node.querySelectorAll("button")].filter(n => n.getClientRects().length).map(n => ({ label: n.textContent.trim(), height: n.getBoundingClientRect().height })) }));
      assert.equal(metrics.overflow, 0);
      assert.ok(metrics.height <= (width === 1440 ? 1100 : 896));
      if (width < 500) assert.ok(metrics.buttons.every(b => b.height >= 44), JSON.stringify(metrics.buttons));
      report.contrast.push(...await scanRenderedContrast(page, { route: "/live-floor", theme, state: `payment-${width}` }));
      report.checks.push({ theme, width, selected, ...metrics });
    }
    await page.setViewportSize({ width: 1440, height: 1100 });
    let closes = 0;
    await page.route("**/sessions/stop/t1?**", async route => { closes++; await new Promise(resolve => setTimeout(resolve, 800)); await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "QA simulated payment failure; no session closed" }) }); });
    const finalize = drawer.getByRole("button", { name: /^Confirm & Close/ });
    await finalize.evaluate(node => node.addEventListener("click", () => {
      const start = performance.now(); const observer = new MutationObserver(() => { if (node.getAttribute("aria-busy") === "true") { window.feedbackMs = performance.now() - start; observer.disconnect(); } }); observer.observe(node, { attributes: true });
    }, { capture: true, once: true }));
    const before = await finalize.boundingBox();
    await finalize.click();
    await page.waitForFunction(() => !!document.querySelector('.checkout-actions-sticky button[aria-busy="true"]'));
    const during = await finalize.boundingBox();
    assert.ok(await drawer.getByRole("button", { name: "Cancel", exact: true }).isDisabled());
    await page.keyboard.press("Escape");
    assert.ok(await drawer.isVisible());
    await page.screenshot({ path: `${directory}/closing-${theme}.png` });
    const feedbackMs = await page.evaluate(() => window.feedbackMs);
    assert.ok(feedbackMs <= 200);
    assert.ok(Math.abs(before.width - during.width) < 1 && Math.abs(before.height - during.height) < 1);
    await drawer.getByRole("alert").waitFor();
    assert.equal(closes, 1);
    report.checks.push({ theme, paymentPendingFeedbackMs: feedbackMs, duplicateCloseRequests: closes - 1, sizeShiftPx: Math.abs(before.width - during.width), pendingDismissBlocked: true, failureKeepsDrawer: true });
    await context.close();
  }
} finally { await browser.close(); await fs.writeFile(`${directory}/results.json`, JSON.stringify(report, null, 2)); }
assert.equal(report.errors.length, 0, JSON.stringify(report.errors));
assert.equal(report.contrast.length, 0, JSON.stringify(report.contrast));
console.log(JSON.stringify(report, null, 2));
